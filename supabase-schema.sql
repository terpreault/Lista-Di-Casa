drop policy if exists "profiles_select_housemates" on public.profiles;
create policy "profiles_select_housemates"
on public.profiles for select to authenticated
using (id = auth.uid() or public.shares_household(id));

drop policy if exists "profiles_update_self" on public.profiles;
create policy "profiles_update_self"
on public.profiles for update to authenticated
using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "households_select_member" on public.households;
create policy "households_select_member"
on public.households for select to authenticated
using (public.is_household_member(id));

drop policy if exists "members_select_same_household" on public.household_members;
create policy "members_select_same_household"
on public.household_members for select to authenticated
using (user_id = auth.uid() or public.is_household_member(household_id));

drop policy if exists "shopping_select_member" on public.shopping_items;
create policy "shopping_select_member"
on public.shopping_items for select to authenticated
using (public.is_household_member(household_id));

drop policy if exists "shopping_insert_member" on public.shopping_items;
create policy "shopping_insert_member"
on public.shopping_items for insert to authenticated
with check (public.is_household_member(household_id) and created_by = auth.uid());

drop policy if exists "shopping_update_member" on public.shopping_items;
create policy "shopping_update_member"
on public.shopping_items for update to authenticated
using (public.is_household_member(household_id))
with check (public.is_household_member(household_id));

drop policy if exists "shopping_delete_member" on public.shopping_items;
create policy "shopping_delete_member"
on public.shopping_items for delete to authenticated
using (public.is_household_member(household_id));

drop policy if exists "tasks_select_member" on public.house_tasks;
create policy "tasks_select_member"
on public.house_tasks for select to authenticated
using (public.is_household_member(household_id));

drop policy if exists "tasks_insert_member" on public.house_tasks;
create policy "tasks_insert_member"
on public.house_tasks for insert to authenticated
with check (public.is_household_member(household_id) and created_by = auth.uid());

drop policy if exists "tasks_update_member" on public.house_tasks;
create policy "tasks_update_member"
on public.house_tasks for update to authenticated
using (public.is_household_member(household_id))
with check (
  public.is_household_member(household_id)
  and (assignee is null or public.shares_household(assignee))
  and (completed_by is null or public.shares_household(completed_by))
);

drop policy if exists "tasks_delete_member" on public.house_tasks;
create policy "tasks_delete_member"
on public.house_tasks for delete to authenticated
using (public.is_household_member(household_id));

grant select, update on public.profiles to authenticated;
grant select on public.households to authenticated;
grant select on public.household_members to authenticated;
grant select, insert, update, delete on public.shopping_items to authenticated;
grant select, insert, update, delete on public.house_tasks to authenticated;

-- Les clients peuvent lire uniquement les événements de leur propre maison.
drop policy if exists "sync_events_select_member" on public.sync_events;
create policy "sync_events_select_member"
on public.sync_events for select to authenticated
using (public.is_household_member(household_id));

grant select on public.sync_events to authenticated;

-- À chaque changement de liste, on écrit un événement minimal contenant
-- uniquement l'identifiant de la maison. Le contenu des listes reste dans
-- les tables protégées par RLS.
create or replace function public.emit_household_sync_event()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  hid uuid;
begin
  if tg_op = 'DELETE' then
    hid := old.household_id;
  else
    hid := new.household_id;
  end if;

  insert into public.sync_events (household_id) values (hid);
  return coalesce(new, old);
end;
$$;

drop trigger if exists shopping_emit_sync on public.shopping_items;
create trigger shopping_emit_sync
after insert or update or delete on public.shopping_items
for each row execute procedure public.emit_household_sync_event();

drop trigger if exists tasks_emit_sync on public.house_tasks;
create trigger tasks_emit_sync
after insert or update or delete on public.house_tasks
for each row execute procedure public.emit_household_sync_event();

